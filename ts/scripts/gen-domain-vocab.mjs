// Bundle spec/vocab/domain-*-v*.txt into src/domain-vocab-data.ts so the library needs no files at runtime.
// The vocabularies are UTF-8 text, so a string literal keeps their exact bytes. src/textdomain.ts checks the SHA-256
// of each bundled copy against the number in the spec (spec/vocab/domains.yaml) before it uses it.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "..", "spec", "vocab");
const files = {};
for (const f of readdirSync(dir).sort()) {
  if (!/^domain-[a-z]+-v\d+\.txt$/.test(f)) continue;
  const raw = readFileSync(join(dir, f));
  const text = raw.toString("utf8");
  if (Buffer.compare(Buffer.from(text, "utf8"), raw) !== 0) throw new Error(`${f} is not valid UTF-8`);
  files[f] = text;
}
const src =
  "// GENERATED by scripts/gen-domain-vocab.mjs from spec/vocab/domain-*-v*.txt. Do not edit.\n" +
  "// Team vocabularies for domain frames (spec section 3.8): file name -> UTF-8 text of the file (one entry per line).\n\n" +
  "export const DOMAIN_VOCAB_TEXT: Record<string, string> = {\n" +
  Object.entries(files).map(([f, t]) => `  ${JSON.stringify(f)}: ${JSON.stringify(t)},\n`).join("") +
  "};\n";
writeFileSync(join(root, "src", "domain-vocab-data.ts"), src);
console.log("wrote src/domain-vocab-data.ts:", Object.keys(files).join(", "));
