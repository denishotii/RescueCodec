// Bundle spec/vocab/text-dict-v*.txt into src/text-dict-data.ts so the library needs no files at runtime.
// The dictionaries are UTF-8 text, so a string literal keeps their exact bytes (checked by a test with SHA-256).
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "..", "spec", "vocab");
const dicts = {};
const hashes = {};
for (const f of readdirSync(dir).sort()) {
  const m = /^text-dict-v(\d+)\.txt$/.exec(f);
  if (!m) continue;
  const raw = readFileSync(join(dir, f));
  const text = raw.toString("utf8");
  if (Buffer.compare(Buffer.from(text, "utf8"), raw) !== 0) throw new Error(`${f} is not valid UTF-8`);
  dicts[m[1]] = text;
  hashes[m[1]] = createHash("sha256").update(raw).digest("hex");
}
const src =
  "// GENERATED by scripts/gen-text-dict.mjs from spec/vocab/text-dict-v*.txt. Do not edit.\n" +
  "// Preset dictionaries for packed texts (spec section 3.5): number -> UTF-8 text of the file.\n\n" +
  "export const TEXT_DICTS: Record<number, string> = {\n" +
  Object.entries(dicts).map(([n, t]) => `  ${n}: ${JSON.stringify(t)},\n`).join("") +
  "};\n\n" +
  "/** SHA-256 of each dictionary file. */\n" +
  "export const TEXT_DICT_SHA256: Record<number, string> = " + JSON.stringify(hashes) + ";\n";
writeFileSync(join(root, "src", "text-dict-data.ts"), src);
console.log("wrote src/text-dict-data.ts: dictionaries", Object.keys(dicts).join(", "));
