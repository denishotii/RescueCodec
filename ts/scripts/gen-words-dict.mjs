// Bundle spec/vocab/words-dict-v*.txt into src/words-dict-data.ts so the library needs no files at runtime.
// The dictionaries are UTF-8 text, so a string literal keeps their exact bytes. src/textwords.ts checks the SHA-256
// of the bundled copy against the number in the spec before it uses it (a damaged copy is never used).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "..", "spec", "vocab");
const dicts = {};
for (const f of readdirSync(dir).sort()) {
  const m = /^words-dict-v(\d+)\.txt$/.exec(f);
  if (!m) continue;
  const raw = readFileSync(join(dir, f));
  const text = raw.toString("utf8");
  if (Buffer.compare(Buffer.from(text, "utf8"), raw) !== 0) throw new Error(`${f} is not valid UTF-8`);
  dicts[m[1]] = text;
}
const src =
  "// GENERATED by scripts/gen-words-dict.mjs from spec/vocab/words-dict-v*.txt. Do not edit.\n" +
  "// Word dictionaries for compact texts (spec section 3.6): number -> UTF-8 text of the file (one entry per line).\n\n" +
  "export const WORD_DICT_TEXT: Record<number, string> = {\n" +
  Object.entries(dicts).map(([n, t]) => `  ${n}: ${JSON.stringify(t)},\n`).join("") +
  "};\n";
writeFileSync(join(root, "src", "words-dict-data.ts"), src);
console.log("wrote src/words-dict-data.ts: dictionaries", Object.keys(dicts).join(", "));
